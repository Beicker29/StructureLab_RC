class StrengthAssumptions(Protocol):
    def max_concrete_strain(self) -> float: ...

    def stress_block_factor(self) -> float: ...

    def beta1(self, fc: float) -> float | None: ...

    def steel_modulus(self) -> float: ...

    def concrete_lambda(self, concrete: str) -> float | None: ...


class Flexure(Protocol):
    def clauses(self) -> dict[str, str]: ...

    def yield_strain(self, fy: float, es: float) -> float: ...

    def strength_reduction_moment(self, et: float, ety: float) -> float: ...

    def min_net_tensile_strain(self, ety: float) -> float: ...

    def beam_axial_limit(self, fc: float, ag: float) -> float: ...

    def min_flexural_reinforcement(self, fc: float, fy: float, bw: float, d: float) -> float: ...

    def effective_min_reinforcement(self, as_min: float, as_analysis: float) -> float: ...

    def crack_control_spacing(self, fy: float, cc: float) -> float: ...

    def skin_reinforcement_depth(self) -> float: ...

    def determinate_flange_width(self, bw: float, bf: float) -> float: ...

    def isolated_flange_width(self, bw: float, hf: float) -> float | None: ...

    def flange_tension_width(self, bf: float, clear_span: float, span: float) -> float: ...


class Shear(Protocol):
    def clauses(self) -> dict[str, str]: ...

    def strength_reduction(self) -> float: ...

    def concrete_shear(
        self,
        *,
        fc: float,
        lam: float,
        bw: float,
        d: float,
        h: float,
        rho_w: float,
        nu: float,
        ag: float,
        vu: float,
        mu: float,
        av_ge_min: bool,
    ) -> float: ...

    def max_stirrup_yield(self) -> float: ...

    def steel_shear(self, av: float, fyt: float, d: float, s: float) -> float: ...

    def max_steel_shear(self, fc: float, bw: float, d: float) -> float: ...

    def min_shear_reinforcement(self, fc: float, bw: float, fyt: float) -> float: ...

    def min_reinforcement_exempt(self, h: float, bw: float, hf: float | None) -> bool: ...

    def min_reinforcement_threshold(
        self, vc: float, fc: float, lam: float, bw: float, d: float, exempt: bool
    ) -> float | None: ...

    def max_spacing(self, vs: float, fc: float, bw: float, d: float) -> float: ...

    def max_leg_spacing_across(self, vs: float, fc: float, bw: float, d: float) -> float | None: ...

    def biaxial_interaction(self, ratio_2: float, ratio_3: float) -> bool | None: ...

    def limited_sqrt_fc(self, fc: float, av_ge_min: bool) -> float: ...

    def punching_concrete_stress(
        self, *, fc: float, lam: float, lam_s: float, beta: float, alpha_s: float, d: float, b0: float
    ) -> float: ...

    def punching_alpha_s(self, sides_outside: int) -> float | None: ...

    def moment_transfer_fraction(self, b1: float, b2: float) -> float: ...

    def effective_slab_width(self, c2: float, h: float) -> float: ...

    def punching_min_reinforcement(
        self, *, vuv: float, fc: float, lam: float, lam_s: float, alpha_s: float, fy: float, b0: float, bslab: float
    ) -> float | None: ...


class Torsion(Protocol):
    def clauses(self) -> dict[str, str]: ...

    def strength_reduction(self) -> float: ...

    def threshold_torsion(self, fc: float, lam: float, acp: float, pcp: float, nu: float, ag: float) -> float: ...

    def effective_overhang(self, h: float, hf: float) -> float: ...

    def max_yield(self) -> float: ...

    def required_transverse(self, tu: float, a0: float, fyt: float) -> float: ...

    def required_longitudinal(self, tu: float, at_s: float, a0: float, ph: float, fyt: float, fy: float) -> float: ...

    def min_transverse(self, fc: float, bw: float, fyt: float) -> float: ...

    def min_longitudinal(self, fc: float, acp: float, fy: float, at_s: float, ph: float, fyt: float, bw: float) -> float: ...

    def combined_stress(self, vu: float, tu: float, bw: float, d: float, ph: float, aoh: float) -> float: ...

    def combined_stress_limit(self, vc: float, fc: float, bw: float, d: float) -> float: ...

    def max_spacing(self, ph: float) -> float: ...

    def max_longitudinal_spacing(self) -> float: ...

    def min_longitudinal_diameter(self, s: float) -> float: ...


class Footing(Protocol):
    def clauses(self) -> dict[str, str]: ...

    def min_reinforcement_ratio(self, fy: float) -> float: ...

    def max_bar_spacing(self, h: float) -> float: ...

    def combined_max_bar_spacing(self, h: float) -> float: ...

    def combined_min_shear_threshold(self, vc: float) -> float | None: ...

    def shrinkage_temperature_ratio(self, fy: float) -> float: ...

    def shrinkage_temperature_max_spacing(self, h: float) -> float: ...

    def band_fraction(self, beta: float) -> float: ...

    def min_depth(self) -> float: ...

    def footing_depth(self, h: float, cover: float, first_db: float, second_db: float) -> float: ...

    def one_way_concrete_shear(
        self, *, fc: float, lam: float, bw: float, d: float, h: float, rho_w: float, vu: float, mu: float
    ) -> float: ...

    def punching_size_factor(self) -> float: ...

    def dowel_min_ratio(self) -> float: ...


class Development(Protocol):
    def clauses(self) -> dict[str, str]: ...

    def min_clear_spacing(self, db: float, aggregate: float) -> float: ...

    def tension_coating_factor(self, coating: str, *, db: float, clear_cover: float, clear_spacing: float) -> float: ...

    def hook_coating_factor(self, coating: str) -> float: ...

    def hook_cover_factor(self, *, db: float, side_cover: float, extension_cover: float) -> float: ...

    def excess_factor_permitted(self, end: str, seismic_level: str) -> bool: ...

    def tension_development_length(
        self, *, fy: float, fc: float, lam: float, db: float, cb: float, concrete_below: float, psi_e: float, excess: float
    ) -> float: ...

    def hook_development_length(
        self, *, fy: float, fc: float, lam: float, db: float, psi_e: float, psi_cc: float, excess: float
    ) -> float: ...

    def compression_development_length(self, *, fy: float, fc: float, lam: float, db: float) -> float: ...


class Bearing(Protocol):
    def clauses(self) -> dict[str, str]: ...

    def strength_reduction(self) -> float: ...

    def nominal_bearing(self, fc: float, a1: float, a2: float) -> float: ...


class DeepBeam(Protocol):
    def clauses(self) -> dict[str, str]: ...

    def section_limit(self, fc: float, bw: float, d: float) -> float: ...

    def min_distributed_ratio(self) -> float: ...

    def max_distributed_spacing(self, d: float) -> float: ...

    def max_curtain_spacing(self, bw: float) -> float | None: ...

    def max_span_to_depth(self) -> float: ...


class Seismic(Protocol):
    def seismic_levels(self) -> frozenset[str]: ...


class Plain(Protocol):
    def clauses(self) -> dict[str, str]: ...

    def strength_reduction(self) -> float: ...

    def flexural_tension_stress(self, fc: float, lam: float) -> float: ...

    def soil_cast_reduction(self) -> float: ...

    def permitted_in_foundations(self, seismic_level: str) -> bool: ...


@dataclass(frozen=True)
class Profile:
    id: str
    strength_assumptions: StrengthAssumptions
    flexure: Flexure
    shear: Shear
    torsion: Torsion
    seismic: Seismic
    footing: Footing
    development: Development
    bearing: Bearing
    plain: Plain
    deep_beam: DeepBeam


